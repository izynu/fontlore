def build_fonts() -> list[dict]:
    fonts = []
    for row in F:
        (slug, family, designer, foundry, lic, cat, cls, scripts, variable,
         axes, weights, note, tags) = row
        if foundry == "Indian Type Foundry" or "ITF" in str(foundry):
            src = f"https://www.fontshare.com/fonts/{slug}"
        elif foundry == "Google" or lic == "Apache-2.0":
            src = f"https://fonts.google.com/specimen/{family.replace(' ', '+')}"
        else:
            src = f"https://fonts.google.com/specimen/{family.replace(' ', '+')}"
        if slug in {"satoshi", "general-sans", "switzer", "cabinet-grotesk", "clash-display",
                    "clash-grotesk", "zodiak", "besley"}:
            src = f"https://www.fontshare.com/fonts/{slug}"
        fonts.append({
            "slug": slug,
            "family": family,
            "designer": designer,
            "foundry": foundry,
            "license": lic,
            "category": cat,
            "classification": cls,
            "scripts": scripts,
            "subsets": scripts,
            "variable": variable,
            "axes": axes,
            "weights": weights,
            "source": src,
            "specimen": src,
            "note": note,
            "tags": tags.split(),
        })
    return fonts


def build_pairings() -> list[dict]:
    out = []
    for i, (h, b, context, why, kind) in enumerate(P, 1):
        out.append({
            "id": f"pair-{i:03d}",
            "heading": h,
            "body": b,
            "context": context,
            "rationale": why,
            "kind": kind,
        })
    return out


def build_tools() -> list[dict]:
    out = []
    for name, url, section, what, access in T:
        out.append({
            "name": name,
            "url": url,
            "section": section,
            "what": what,
            "access": access,
        })
    return out


def main() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    fonts = build_fonts()
    pairings = build_pairings()
    tools = build_tools()
    (DATA / "fonts.json").write_text(
        json.dumps({"count": len(fonts), "fonts": fonts}, indent=2) + "\n", encoding="utf-8")
    (DATA / "pairings.json").write_text(
        json.dumps({"count": len(pairings), "pairings": pairings}, indent=2) + "\n", encoding="utf-8")
    (DATA / "tools.json").write_text(
        json.dumps({"count": len(tools), "tools": tools}, indent=2) + "\n", encoding="utf-8")
    cats: dict[str, int] = {}
    for f in fonts:
        cats[f["category"]] = cats.get(f["category"], 0) + 1
    print(f"fonts: {len(fonts)}  by category: {cats}")
    print(f"pairings: {len(pairings)}")
    print(f"tools: {len(tools)}")


